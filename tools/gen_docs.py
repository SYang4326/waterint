"""Generate the docs-site reference pages from the package registry (WaterInt v0.7).

    python tools/gen_docs.py --site ../water-interface-analysis-site

Writes, under <site>/docs/reference/:
    index.html            all analyses by group (kind, backends, summary)
    <analysis>.html       one page per analysis: parameters with defaults, kernels/backends, config snippet, CLI
    profiles.html         system profiles shipped with the package
    backends.html         kernel registry (python / cpu / gpu implementations)
    analyses.json         the same data, machine-readable (registry.describe())
and rewrites the sidebar navigation of every page of the site, so hand-written pages and generated pages share one
menu. Nothing here is edited by hand: change the analysis class (description, params) and rerun.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import subprocess
from pathlib import Path
from typing import Any

import yaml

from waterint import registry
from waterint.backends import registry as kernels

PKG = Path(registry.__file__).resolve().parent
REPO = PKG.parents[1]
THEORY = {"density": "docs/density.html", "orientation": "docs/oh_orientation.html", "hbond": "docs/hbond.html",
          "sfg": "docs/sfg.html", "sfg-species": "docs/sfg.html"}
KIND_TEXT = {"stream": "per frame (one pass with the other analyses)",
             "block": "blocks of frames (batched C++/GPU kernels, same single pass)",
             "post": "post-processing (results of earlier analyses or files; no trajectory)"}
NAV = [
    ("Start", [("Overview", "index.html"), ("Getting Started", "getting_started.html"),
               ("Architecture", "docs/architecture.html"), ("Pipeline Runs", "docs/pipeline.html"),
               ("Config Reference", "docs/config_reference.html")]),
    ("Theory", [("Density Profile", "docs/density.html"), ("OH Orientation", "docs/oh_orientation.html"),
                ("H-Bond Analysis", "docs/hbond.html"), ("SFG Spectrum", "docs/sfg.html")]),
    ("Reference (generated)", [("All Analyses", "docs/reference/index.html"),
                               ("System Profiles", "docs/reference/profiles.html"),
                               ("Backends", "docs/reference/backends.html")]),
    ("Tools", [("Local UI", "docs/local_ui.html"), ("Adding An Analysis", "docs/analysis_template.html"),
               ("Interactive Demos", "demos/index.html")]),
]
PREP_KERNELS = {"ownership", "hbonds"}
NAV_RE = re.compile(r'<nav aria-label="Documentation navigation">.*?</nav>', re.S)
e = html.escape


def version_line() -> str:
    try:
        sha = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                             check=True).stdout.strip()
    except Exception:
        sha = "unknown"
    m = re.search(r'^version\s*=\s*"([^"]+)"', (REPO / "pyproject.toml").read_text(encoding="utf-8"), re.M)
    return f"waterint {m.group(1) if m else '0.7'}, commit {sha}"


def nav_html(prefix: str, indent: str = "        ") -> str:
    out = [f'{indent}<nav aria-label="Documentation navigation">']
    for heading, items in NAV:
        out += [f'{indent}  <div class="nav-section">', f'{indent}    <p class="nav-heading">{e(heading)}</p>',
                f'{indent}    <ul class="nav-list">']
        out += [f'{indent}      <li><a href="{prefix}{href}">{e(label)}</a></li>' for label, href in items]
        out += [f"{indent}    </ul>", f"{indent}  </div>"]
    out.append(f"{indent}</nav>")
    return "\n".join(out).lstrip()


def page(title: str, body: str, toc: list[tuple[str, str]], prefix: str, footer: str) -> str:
    toc_html = "\n".join(f'        <a href="#{a}">{e(t)}</a>' for a, t in toc)
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{e(title)} - WaterInt</title>
    <link rel="stylesheet" href="{prefix}assets/styles.css" />
  </head>
  <body>
    <div class="mobile-topbar">
      <strong>WaterInt</strong>
      <button data-nav-toggle type="button">Menu</button>
    </div>
    <div class="site-shell">
      <aside class="sidebar">
        <div class="brand">
          <a class="brand-title" href="{prefix}index.html">WaterInt</a>
          <span class="brand-subtitle">Config-driven analysis for water-containing molecular simulations.</span>
        </div>
        {nav_html(prefix)}
      </aside>
      <main class="content">
        <article class="doc">
{body}
          <footer class="footer">Generated by <code>tools/gen_docs.py</code> from {e(footer)}. Do not edit by hand.</footer>
        </article>
      </main>
      <aside class="toc" aria-label="On this page">
        <p class="toc-title">On This Page</p>
{toc_html}
      </aside>
    </div>
    <script src="{prefix}assets/site.js"></script>
  </body>
</html>
"""


def fmt_default(value: Any) -> str:
    if value == "required":
        return "required"
    if value is None:
        return "none"
    return json.dumps(value) if not isinstance(value, str) else value


def snippet(a: dict[str, Any]) -> str:
    """Pipeline config entry: required parameters as placeholders, everything else at its default (omitted)."""
    entry: dict[str, Any] = {"type": a["name"], "name": f"my_{a['name'].replace('-', '_')}"}
    notes = []
    for key, p in a["params"].items():
        if p["default"] != "required":
            continue
        node = entry
        parts = key.split(".")
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = f"<{parts[-1]}>"
        notes.append(f"# <{parts[-1]}>: {p['help']}")
    text = yaml.safe_dump({"analyses": [entry]}, sort_keys=False, default_flow_style=False).rstrip()
    return text + ("\n" + "\n".join(notes) if notes else "")


def analysis_page(a: dict[str, Any], footer: str) -> str:
    rows = "\n".join(
        f"              <tr><td><code>{e(k)}</code></td><td><code>{e(fmt_default(p['default']))}</code></td>"
        f"<td>{e(str(p['help']))}</td></tr>" for k, p in a["params"].items())
    own = {k: b for k, b in a["kernels"].items() if k.split(".")[0] not in PREP_KERNELS}
    shared = {k: b for k, b in a["kernels"].items() if k.split(".")[0] in PREP_KERNELS}
    krows = "\n".join(f"              <tr><td><code>{e(k)}</code></td><td>{e(', '.join(b))}</td><td>this analysis</td></tr>"
                      for k, b in sorted(own.items())) or "              <tr><td>-</td><td>numpy</td><td>this analysis</td></tr>"
    krows += "".join(f"\n              <tr><td><code>{e(k)}</code></td><td>{e(', '.join(b))}</td>"
                     f"<td>shared prep (<code>prep.backend</code>)</td></tr>" for k, b in sorted(shared.items()))
    theory = THEORY.get(a["name"])
    theory_html = f'<p>Theory, definitions and example results: <a href="../../{theory}">{e(theory.split("/")[-1][:-5].replace("_", " "))} page</a>.</p>' if theory else ""
    aliases = f" Aliases: {', '.join(f'<code>{e(x)}</code>' for x in a['aliases'])}." if a["aliases"] else ""
    body = f"""          <h1>{e(a['name'])}</h1>
          <p class="lead">{e(a['description'])}</p>
          <div class="version-row">
            <span class="badge">group: {e(a['group'])}</span>
            <span class="badge">kind: {e(a['kind'])}</span>
          </div>
          <section id="summary">
            <h2>Summary</h2>
            <p>Runs {e(KIND_TEXT.get(a['kind'], a['kind']))}.{aliases}</p>
            {theory_html}
          </section>
          <section id="parameters">
            <h2>Parameters</h2>
            <p>Keys are relative to the analysis entry in <code>analyses:</code>; dotted keys are nested mappings.
            System-specific values (cutoffs, species tables, reference plane, windows) come from the
            <a href="profiles.html">system profile</a> unless overridden.</p>
            <table>
              <thead><tr><th>Key</th><th>Default</th><th>Meaning</th></tr></thead>
              <tbody>
{rows}
              </tbody>
            </table>
          </section>
          <section id="backends">
            <h2>Kernels And Backends</h2>
            <p>Select with <code>backend: auto | python | cpu | gpu</code>; <code>auto</code> takes the fastest available
            implementation and records the one used in the result metadata. See <a href="backends.html">Backends</a>.</p>
            <table>
              <thead><tr><th>Kernel</th><th>Implementations</th><th>Used by</th></tr></thead>
              <tbody>
{krows}
              </tbody>
            </table>
          </section>
          <section id="config">
            <h2>Config Snippet</h2>
            <pre><code>{e(snippet(a))}</code></pre>
          </section>
          <section id="cli">
            <h2>Command Line</h2>
            <pre><code># several analyses in one pass (the entry above inside analyses:)
waterint run run.yaml
# this analysis alone, v0.6-style config
waterint {e(a['name'])} --config config.yaml</code></pre>
          </section>"""
    toc = [("summary", "Summary"), ("parameters", "Parameters"), ("backends", "Kernels And Backends"),
           ("config", "Config Snippet"), ("cli", "Command Line")]
    return page(a["name"], body, toc, "../../", footer)


def index_page(items: list[dict[str, Any]], footer: str) -> str:
    sections, toc = [], []
    for group, names in registry.GROUPS.items():
        gid = group.replace(" ", "-")
        cards = []
        for name in names:
            a = next(x for x in items if x["name"] == name)
            backends = sorted({b for impls in a["kernels"].values() for b in impls}) or ["python"]
            cards.append(f"""              <a class="card module-card" href="{e(name)}.html">
                <span class="module-meta">{e(a['kind'])} &middot; {e(', '.join(backends))}</span>
                <h3>{e(name)}</h3>
                <p>{e(a['description'])}</p>
              </a>""")
        sections.append(f"""          <section id="{gid}">
            <h2>{e(group.title())}</h2>
            <div class="grid two">
{chr(10).join(cards)}
            </div>
          </section>""")
        toc.append((gid, group.title()))
    body = f"""          <h1>All Analyses</h1>
          <p class="lead">Every analysis registered in the package ({len(items)}), generated from
          <code>waterint.registry</code>. Any number of them run together in one pass with <code>waterint run</code>.</p>
          <div class="admonition">
            <p class="admonition-title">Kinds</p>
            <p><b>stream</b>: called once per prepared frame. <b>block</b>: gets arrays of many frames for batched kernels.
            <b>post</b>: no trajectory, reads results of earlier analyses in the same run (by name) or files.</p>
          </div>
{chr(10).join(sections)}"""
    return page("All Analyses", body, toc, "../../", footer)


def profiles_page(footer: str) -> str:
    sections, toc = [], []
    for path in sorted((PKG / "system" / "profiles").glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        pid = path.stem
        head = []
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.startswith("#"):
                break
            head.append(line.lstrip("# ").rstrip())
        note = data.get("description") or " ".join(head)
        sections.append(f"""          <section id="{e(pid)}">
            <h2>{e(pid)}</h2>
            {f'<p>{e(str(note))}</p>' if note else ''}
            <pre><code>{e(path.read_text(encoding='utf-8').rstrip())}</code></pre>
          </section>""")
        toc.append((pid, pid))
    body = f"""          <h1>System Profiles</h1>
          <p class="lead">A profile holds everything system-specific: type map, H-ownership rule and cutoff, solid
          definition, species tables, reference plane, z windows, formal charges. Changing the solid means changing the
          profile, never the code.</p>
          <pre><code>system:
  profile: generic_oxide_water        # a shipped profile by name
  # profile: my_surface.yaml          # or a file
  # profile: {{extends: generic_oxide_water, solid: {{mode: frozen}}}}   # or an inline override</code></pre>
          <p>Show a resolved profile with <code>waterint profile &lt;name&gt;</code>.</p>
{chr(10).join(sections)}"""
    return page("System Profiles", body, toc, "../../", footer)


def backends_page(footer: str) -> str:
    rows = "\n".join(f"              <tr><td><code>{e(k)}</code></td><td>{e(', '.join(v))}</td></tr>"
                     for k, v in sorted(kernels.describe().items()))
    body = f"""          <h1>Backends</h1>
          <p class="lead">Heavy kernels have one signature and up to three implementations. The Python reference is always
          present; the C++ (OpenMP) library compiles on first use and is cached by source hash; CUDA kernels are imported
          only when an analysis asks for <code>gpu</code>. The core package runs without a compiler or CUDA.</p>
          <section id="select">
            <h2>Choosing A Backend</h2>
            <pre><code>analyses:
  - type: hb-correlation
    name: hbc
    backend: gpu          # auto | python | cpu | gpu
prep:
  backend: auto           # ownership / species / H-bond kernels</code></pre>
            <p>An explicit request that cannot be met is an error; <code>auto</code> falls back and records the backend used
            in each result's metadata. <code>waterint backends</code> prints availability on the current machine.</p>
          </section>
          <section id="kernels">
            <h2>Registered Kernels</h2>
            <table>
              <thead><tr><th>Kernel</th><th>Implementations</th></tr></thead>
              <tbody>
{rows}
              </tbody>
            </table>
          </section>"""
    return page("Backends", body, [("select", "Choosing A Backend"), ("kernels", "Registered Kernels")], "../../", footer)


def rewrite_nav(site: Path) -> list[Path]:
    changed = []
    for path in sorted(site.rglob("*.html")):
        rel = path.relative_to(site)
        if rel.parts[0] in {"public", "test", "node_modules"}:
            continue
        text = path.read_text(encoding="utf-8")
        prefix = "../" * (len(rel.parts) - 1)
        new = NAV_RE.sub(lambda m: nav_html(prefix), text, count=1)
        if new != text:
            path.write_text(new, encoding="utf-8", newline="\n")
            changed.append(rel)
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--site", required=True, help="docs site root (contains index.html)")
    args = ap.parse_args(argv)
    site = Path(args.site).resolve()
    if not (site / "index.html").exists():
        raise SystemExit(f"not a site root: {site}")
    out = site / "docs" / "reference"
    out.mkdir(parents=True, exist_ok=True)
    footer = version_line()
    items = registry.describe()
    for a in items:
        (out / f"{a['name']}.html").write_text(analysis_page(a, footer), encoding="utf-8", newline="\n")
    (out / "index.html").write_text(index_page(items, footer), encoding="utf-8", newline="\n")
    (out / "profiles.html").write_text(profiles_page(footer), encoding="utf-8", newline="\n")
    (out / "backends.html").write_text(backends_page(footer), encoding="utf-8", newline="\n")
    (out / "analyses.json").write_text(json.dumps({"generated_from": footer, "analyses": items}, indent=2, default=str) + "\n",
                                       encoding="utf-8", newline="\n")
    known = {f"{a['name']}.html" for a in items} | {"index.html", "profiles.html", "backends.html", "analyses.json"}
    stale = sorted(p.name for p in out.iterdir() if p.name not in known)
    nav = rewrite_nav(site)
    print(f"{len(items)} analysis pages + index/profiles/backends -> {out}")
    print(f"navigation rewritten in {len(nav)} pages")
    if stale:
        print(f"stale files in {out} (not from the registry): {stale}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
